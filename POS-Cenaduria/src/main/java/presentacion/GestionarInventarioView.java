/** Tamaño total del panel, calculado a partir del layout absoluto. */
private Dimension tamanoPanel() {
    Dimension d = getPreferredSize();
    if (d.width < 400 || d.height < 300) {
        d = jLabel_Fondo.getPreferredSize();
    }
    return d;
}

private void configurarMenu() {
    Dimension total = tamanoPanel();
    int anchoMenu = (int) (total.width * PROPORCION_MENU);
    int anchoBoton = anchoMenu - 50;

    String[] opciones = {"Inicio", "Punto de venta", "Inventario", "Reportes", "Usuarios", "Configuración"};

    JPanel menu = new JPanel();
    menu.setLayout(new BoxLayout(menu, BoxLayout.Y_AXIS));
    menu.setOpaque(false);

    for (String opcion : opciones) {
        boolean activo = opcion.equals("Inventario");
        BotonRedondeado b = new BotonRedondeado(opcion, activo ? NARANJA : null);
        b.setFont(new Font("Segoe UI", Font.BOLD, 14));
        b.setForeground(Color.WHITE);
        b.setHorizontalAlignment(SwingConstants.LEFT);
        b.setBorder(new EmptyBorder(9, 16, 9, 16));
        b.setAlignmentX(Component.LEFT_ALIGNMENT);
        Dimension tam = new Dimension(anchoBoton, 40);
        b.setPreferredSize(tam);
        b.setMaximumSize(tam);
        b.addActionListener(e ->
                JOptionPane.showMessageDialog(this, "Pantalla \"" + opcion + "\" pendiente"));
        menu.add(b);
        menu.add(Box.createRigidArea(new Dimension(0, 6)));
    }

    // índice 0 = al frente, para que quede por encima de jLabel_Fondo
    add(menu, new AbsoluteConstraints(25, MENU_Y, anchoBoton, opciones.length * 46), 0);
}

private void configurarContenido() {
    Dimension total = tamanoPanel();
    int xContenido = (int) (total.width * PROPORCION_MENU);

    PanelInventario panel = new PanelInventario();

    // Datos de prueba (luego se reemplazan por los de la base de datos)
    List<Insumo> prueba = new ArrayList<>();
    prueba.add(new Insumo(1L, "Jitomate", 2, EstadoInsumo.BAJO, UnidadInsumo.KG, CategoriaInsumo.VERDURAS, null));
    prueba.add(new Insumo(2L, "Cebolla", 1, EstadoInsumo.AGOTADO, UnidadInsumo.KG, CategoriaInsumo.VERDURAS, null));
    prueba.add(new Insumo(3L, "Queso", 1, EstadoInsumo.AGOTADO, UnidadInsumo.KG, CategoriaInsumo.CARNES, null));
    prueba.add(new Insumo(4L, "Pechuga de pollo", 8, EstadoInsumo.DISPONIBLE, UnidadInsumo.KG, CategoriaInsumo.CARNES, null));
    panel.setInsumos(prueba);

    panel.setAccionAgregar(() ->
            JOptionPane.showMessageDialog(this, "Aquí irá el formulario de nuevo insumo"));
    panel.setAccionEditar(i ->
            JOptionPane.showMessageDialog(this, "Editar: " + i.getNombreInsumo()));
    panel.setAccionEliminar(i ->
            JOptionPane.showMessageDialog(this, "Eliminar: " + i.getNombreInsumo()));

    add(panel, new AbsoluteConstraints(xContenido, 0, total.width - xContenido, total.height), 0);

    revalidate();
    repaint();
}


